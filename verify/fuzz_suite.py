"""Deterministic loader fuzz gate.

Generates seed-fixed mutations of real corpus alignments (truncations, byte flips,
line surgery, control/high bytes), writes them with a manifest, and runs the strict
differential harness (verify/differential.py) over every case. Byte equality of
rc/stderr/stdout/files is required; the harness classifies native crashes/UB
separately and never counts them as matches. Run on Linux/WSL:
    python3 verify/fuzz_suite.py                    # generate + run (label "fuzz")
    python3 verify/fuzz_suite.py --generate-only

Every label is a fixed seed with its own corpus directory and manifest, so any label
can be regenerated byte-for-byte:
    python3 verify/fuzz_suite.py --label fuzz2       # generate + run
    python3 verify/fuzz_suite.py --all               # every label
    python3 verify/fuzz_suite.py --all --generate-only

`--soft-ratio` is the share of mutants built from edits that keep the input loadable
(rewrapped sequences, edited headers, appended blank lines, ...). The kind of such a
mutation is part of the file name, so a report shows which kinds the reference
accepts. The default label draws no soft mutation, which leaves its manifest exactly
as it was when the gate was introduced.
"""
import argparse
from pathlib import Path
import random
import shlex
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "verify"))

import differential  # noqa: E402  (VALUE_OPTIONS, for the completeness check)

MUTATIONS_PER_BASE = 20
FORMATS = ["-fasta", "-phylip", "-clustal", "-sgt"]

# label -> (seed, share of load-preserving mutants)
LABELS = {
    "fuzz": (90210, 0.0),
    "fuzz2": (90211, 0.5),
    "fuzz3": (90212, 0.85),
}


def bases():
    dataset = ROOT / "upstream/dataset"
    names = ["example.001.AA.clw", "example.001.AA.msl", "example.001.AA.phy",
             "example.002.AA.phy", "example.004.AA.fasta", "example.006.AA.pir",
             "example.007.AA.fasta", "example.094.DNADeg.sequential_phy"]
    files = [(dataset / n) for n in names if (dataset / n).is_file()]
    ext = ROOT / "verify/corpus/extended/ext_in.pir"
    if ext.is_file():
        files.append(ext)
    return files


def mutate(data, rng):
    kind = rng.randrange(9)
    if kind == 0:  # truncate
        return data[:max(1, int(len(data) * rng.choice([0.05, 0.25, 0.5, 0.75, 0.9])))]
    if kind == 1:  # random byte flips
        out = bytearray(data)
        for _ in range(rng.randrange(1, 8)):
            if out:
                out[rng.randrange(len(out))] = rng.randrange(256)
        return bytes(out)
    if kind == 2:  # delete a line
        lines = data.split(b"\n")
        if len(lines) > 2:
            del lines[rng.randrange(len(lines) - 1)]
        return b"\n".join(lines)
    if kind == 3:  # duplicate a line
        lines = data.split(b"\n")
        if len(lines) > 2:
            i = rng.randrange(len(lines) - 1)
            lines.insert(i, lines[i])
        return b"\n".join(lines)
    if kind == 4:  # inject control / high bytes at random offsets
        out = bytearray(data)
        for _ in range(rng.randrange(1, 6)):
            out.insert(rng.randrange(len(out) + 1),
                       rng.choice([0, 9, 13, 0xE9, 0x3B, 0x7B]))
        return bytes(out)
    if kind == 5:  # CRLF everything
        return data.replace(b"\n", b"\r\n")
    if kind == 6:  # strip all newlines (one giant line)
        return data.replace(b"\n", b"")
    if kind == 7:  # shuffle lines (keeps lengths, scrambles blocks)
        lines = data.split(b"\n")
        rng.shuffle(lines)
        return b"\n".join(lines)
    # kind == 8: swap two random bytes
    out = bytearray(data)
    if len(out) > 2:
        i, j = rng.randrange(len(out)), rng.randrange(len(out))
        out[i], out[j] = out[j], out[i]
    return bytes(out)


# ---------------------------------------------------------------------------
# Load-preserving ("soft") edits. Each returns (kind, bytes).
# ---------------------------------------------------------------------------

def _soft_tail(data, rng):
    stripped = data.rstrip(b"\r\n")
    return "tail", (stripped if stripped != data else data + b"\n")


def _soft_blank(data, rng):
    return "blank", data.rstrip(b"\r\n") + b"\n" * rng.randrange(2, 5)


def _fasta_records(data):
    records, header, chunks = [], None, []
    for line in data.split(b"\n"):
        if line.startswith(b">"):
            if header is not None:
                records.append([header, b"".join(chunks)])
            header, chunks = line, []
        elif header is not None:
            chunks.append(line.rstrip(b"\r"))
    if header is not None:
        records.append([header, b"".join(chunks)])
    return records


def _fasta_emit(records, width):
    return b"".join(header + b"\n" + _wrap(seq, width)
                    for header, seq in records)


def _wrap(seq, width):
    return b"".join(seq[i:i + width] + b"\n" for i in range(0, len(seq), width))


def _soft_fasta_wrap(data, rng):
    return "wrap", _fasta_emit(_fasta_records(data), rng.choice([10, 17, 23, 45, 80, 120]))


def _soft_fasta_header(data, rng):
    lines = data.split(b"\n")
    headers = [i for i, line in enumerate(lines) if line.startswith(b">")]
    if not headers:
        return _soft_tail(data, rng)
    i = rng.choice(headers)
    name = lines[i].partition(b" ")[0].rstrip(b"\r")
    lines[i] = (name + rng.choice([b"", b" description", b" " + b"x" * rng.randrange(1, 30),
                                   b" tag:a,b;c"])).rstrip()
    return "header", b"\n".join(lines)


def _soft_fasta_case(data, rng):
    lines = data.split(b"\n")
    candidates = [(i, j) for i, line in enumerate(lines)
                  if line and not line.startswith(b">")
                  for j in range(len(line)) if 65 <= line[j] <= 90 or 97 <= line[j] <= 122]
    if not candidates:
        return _soft_tail(data, rng)
    i, j = rng.choice(candidates)
    lines[i] = lines[i][:j] + bytes([lines[i][j] ^ 0x20]) + lines[i][j + 1:]
    return "case", b"\n".join(lines)


def _soft_fasta_dup(data, rng):
    records = _fasta_records(data)
    if not records:
        return _soft_tail(data, rng)
    records.append(list(records[rng.randrange(len(records))]))
    return "duprec", _fasta_emit(records, rng.choice([60, 80]))


def _soft_fasta_trail(data, rng):
    lines = data.split(b"\n")
    for i, line in enumerate(lines):
        if line and not line.startswith(b">") and rng.random() < 0.5:
            lines[i] = line + b" " * rng.randrange(1, 4)
    return "trailsp", b"\n".join(lines)


def _soft_clw_consensus(data, rng):
    lines = [line for line in data.split(b"\n")
             if not line.lstrip().startswith((b"*", b":"))]
    return "consens", b"\n".join(lines)


def _soft_clw_header(data, rng):
    # trimAl recognises CLUSTAL input by a first line starting with "CLUSTAL"; keep it.
    lines = data.split(b"\n")
    if lines:
        lines[0] = rng.choice([b"CLUSTAL O(1.83) multiple sequence alignment",
                               b"CLUSTAL", b"CLUSTAL 2.1 multiple sequence alignment"])
    return "clwhead", b"\n".join(lines)


def _soft_clw_space(data, rng):
    lines = data.split(b"\n")
    for i, line in enumerate(lines):
        name, sep, rest = line.partition(b"  ")
        if sep and not line.startswith((b" ", b"\t")):
            lines[i] = name + b" " * rng.choice([2, 3, 5, 9]) + rest
    return "clwspace", b"\n".join(lines)


def _soft_block_wrap(data, rng, start, stop):
    """Rewrap the sequence lines of every block that starts with `start`. A block ends
    at its terminator line: '*' for PIR, a blank line or the next '#' for MEGA. PIR
    keeps one title line after the header; MEGA has none."""
    lines = data.split(b"\n")
    out, i = [], 0
    while i < len(lines):
        if not lines[i].startswith(start):
            out.append(lines[i])
            i += 1
            continue
        j = i + 1
        while j < len(lines) and lines[j].strip():
            if stop is None and lines[j].startswith(start):
                break
            j += 1
        pir = stop is not None
        out.append(lines[i])
        body = i + 1 + (1 if pir and j - i - 1 >= 1 else 0)
        out.extend(lines[i + 1:body])
        out.append(_wrap(b"".join(lines[body:j]), rng.choice([10, 30, 60, 80])))
        if j < len(lines):
            out.append(lines[j])
        i = j + 1
    return b"\n".join(out)


def _soft_pir_wrap(data, rng):
    return "wrap", _soft_block_wrap(data, rng, b">", b"*")


def _soft_pir_title(data, rng):
    lines = data.split(b"\n")
    for i, line in enumerate(lines):
        if line.startswith(b">") and i + 1 < len(lines):
            title = lines[i + 1].rstrip(b"\r")
            lines[i + 1] = rng.choice([b"edited title", title + b" longer",
                                       b"t" * rng.randrange(1, 40)])
            break
    return "pirhead", b"\n".join(lines)


def _soft_mega_wrap(data, rng):
    return "wrap", _soft_block_wrap(data, rng, b"#", None)


SOFT_KINDS = {
    "fasta": [_soft_fasta_wrap, _soft_fasta_header, _soft_fasta_case, _soft_fasta_dup,
              _soft_fasta_trail],
    "clw": [_soft_clw_consensus, _soft_clw_header, _soft_clw_space],
    "pir": [_soft_pir_wrap, _soft_pir_title],
    "msl": [_soft_mega_wrap],
}


def mutate_soft(data, rng, suffix):
    kinds = [_soft_tail, _soft_blank] + SOFT_KINDS.get(suffix, [])
    return rng.choice(kinds)(data, rng)


def check_rows(rows):
    """Every row must be a complete command. A row that ends on a value option never
    reaches the loader: the reference only reports the broken argument, on both
    sides, and the whole suite degenerates into an argument-error test."""
    for row in rows:
        tokens = shlex.split(row)
        if not tokens or tokens[-1] in differential.VALUE_OPTIONS or "$OUT" not in tokens:
            raise SystemExit("incomplete fuzz case: " + row)


def generate(label, seed, soft_ratio, mutations):
    corpus = ROOT / "verify/corpus" / label
    manifest = ROOT / ("verify/%s_manifest.txt" % label)
    if not label.replace("_", "").isalnum():
        raise SystemExit("label must be alphanumeric: " + label)
    if corpus.exists():
        shutil.rmtree(corpus)
    corpus.mkdir(parents=True)
    rng = random.Random(seed)
    rows = []
    index = 0
    for base in bases():
        data = base.read_bytes()
        if not data:
            continue
        for m in range(mutations):
            soft = soft_ratio > 0 and rng.random() < soft_ratio
            if soft:
                kind, mutant = mutate_soft(data, rng, base.suffix.lstrip(".").lower())
                tag = "_" + kind
            else:
                mutant, tag = mutate(data, rng), ""
            path = corpus / ("%s_%02d_%02d%s.bin" % (base.stem, index, m, tag))
            path.write_bytes(mutant)
            relative = path.relative_to(ROOT).as_posix()
            flags = FORMATS[m % len(FORMATS)]
            rows.append(f"-in {relative} {flags} -out $OUT")
            index += 1
    check_rows(rows)
    header = "# Generated by verify/fuzz_suite.py, seed=%d" % seed
    if soft_ratio:
        header += " soft_ratio=%g" % soft_ratio
    manifest.write_text(header + "\n" + "\n".join(rows) + "\n", encoding="utf-8", newline="\n")
    print("FUZZ label=%s cases=%d seed=%d soft_ratio=%g" % (label, len(rows), seed, soft_ratio))
    return manifest


def run(manifest, timeout, jobs, jar=None):
    command = [sys.executable, str(ROOT / "verify/differential.py"),
               str(manifest), "--timeout", str(timeout), "--jobs", str(jobs)]
    if jar:
        command += ["--jar", jar]
    return subprocess.run(command).returncode


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--generate-only", action="store_true")
    parser.add_argument("--label", choices=sorted(LABELS), default="fuzz")
    parser.add_argument("--all", action="store_true", help="every label in LABELS")
    parser.add_argument("--seed", type=int, help="override the label's seed")
    parser.add_argument("--soft-ratio", type=float, help="override the label's share of soft mutants")
    parser.add_argument("--mutations", type=int, default=MUTATIONS_PER_BASE)
    parser.add_argument("--timeout", type=int, default=60)
    parser.add_argument("--jobs", type=int, default=3)
    parser.add_argument("--jar", help="JAR to test (default: java/target/trimal.jar)")
    options = parser.parse_args()
    labels = sorted(LABELS) if options.all else [options.label]
    status = 0
    for label in labels:
        seed, soft_ratio = LABELS[label]
        if options.seed is not None:
            seed = options.seed
        if options.soft_ratio is not None:
            soft_ratio = options.soft_ratio
        manifest = generate(label, seed, soft_ratio, options.mutations)
        if not options.generate_only:
            print("RUN", label, flush=True)
            status = max(status, run(manifest, options.timeout, options.jobs, options.jar))
    return status


if __name__ == "__main__":
    sys.exit(main())
