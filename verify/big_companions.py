"""Generate the readal / statal gate manifests for the downloaded eggNOG clusters.

Every aligned alignment under verify/corpus/eggnog/*.faa gets each conversion or
statistic listed below. The lists contain only options the reference tools accept:
readal has no -out-less stdout conversion and no -keepheader, statal has neither -out
nor -soverlap. An earlier hand-written manifest mixed exactly those in, so the
reference rejected 40 of its 64 cases before reading any input, and those cases
compared error messages only. With the lists kept here that cannot creep back, and
the harness's VACUITY line shows how many cases the reference accepted.

    python3 verify/big_companions.py            # write both manifests
    python3 verify/big_companions.py --check    # fail if the manifests on disk differ
"""
import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
CORPUS = ROOT / "verify/corpus/eggnog"

# conversions written to -out
READAL_FILES = ["-clustal", "-phylip", "-phylip_m10", "-phylip_paml", "-nexus", "-mega",
                "-nbrf", "-fasta_m10", "-reverse -fasta"]
# information printed to stdout
READAL_STDOUT = ["-format -type -info"]
STATAL = ["-sgc", "-sgt", "-sident", "-scolidentt", "-sgc -sgt -sident -scolidentt",
          "-ssc -sst", "-sgc -w 5"]


def manifests():
    # *.prefix.faa is the unaligned remainder of a truncated member: every method
    # rejects it with the same message, so one case per tool covers it.
    aligned = sorted(path for path in CORPUS.glob("*.faa") if not path.name.endswith(".prefix.faa"))
    unaligned = sorted(CORPUS.glob("*.prefix.faa"))
    if not aligned:
        raise SystemExit("no eggNOG corpus under " + CORPUS.relative_to(ROOT).as_posix()
                         + " (run verify/eggnog_stream.py first)")
    count = "%d aligned alignments" % len(aligned) + (
        " and the unaligned remainder of a truncated member" if unaligned else "")
    readal = ["# tool: readal", "# Generated by verify/big_companions.py: " + count]
    statal = ["# tool: statal", "# Generated by verify/big_companions.py: " + count]
    for alignment in alignments(aligned):
        readal += ["-in %s %s -out $OUT" % (alignment, flags) for flags in READAL_FILES]
        readal += ["-in %s %s" % (alignment, flags) for flags in READAL_STDOUT]
        statal += ["-in %s %s" % (alignment, flags) for flags in STATAL]
    for alignment in alignments(unaligned):
        readal += ["-in %s -phylip -out $OUT" % alignment]
        statal += ["-in %s -sgc" % alignment]
    return {"readal_big_manifest.txt": "\n".join(readal) + "\n",
            "statal_big_manifest.txt": "\n".join(statal) + "\n"}


def alignments(paths):
    return [path.relative_to(ROOT).as_posix() for path in paths]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    status = 0
    for name, content in manifests().items():
        path = ROOT / "verify" / name
        cases = sum(1 for line in content.splitlines() if not line.startswith("#"))
        if options.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                print("DIFFERS " + name)
                status = 1
            else:
                print("OK %s cases=%d" % (name, cases))
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
            print("WROTE verify/%s cases=%d" % (name, cases))
    return status


if __name__ == "__main__":
    sys.exit(main())
